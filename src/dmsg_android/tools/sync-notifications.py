#!/usr/bin/env python3
"""Sync public, content-free notification vocabulary shared with iOS."""
import argparse
import pathlib
import plistlib
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parents[3]
KEYS = {
    "notice_channel_security": "Account security",
    "notice_channel_action": "dmsg.noticeNeedsAction",
    "notice_channel_message": "dmsg.noticeMessages",
    "notice_channel_service": "dmsg.noticeServices",
    "notice_body_security": "dmsg.noticeSecurityBody",
    "notice_body_action": "dmsg.noticeActionBody",
    "notice_body_message": "dmsg.noticeMessageBody",
    "notice_body_service": "dmsg.noticeServiceBody",
    "notice_body_generic": "dmsg.noticeUpdatesBody",
    "notice_test": "dmsg.noticeTest",
}

def render(values):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/sync-notifications.py from the shared iOS vocabulary. -->', '<resources>']
    for name, key in KEYS.items():
        text = values[key].replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"')
        lines.append(f'    <string name="{name}">{escape(text)}</string>')
    return "\n".join(lines + ["</resources>", ""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {}
    for source in sorted((ROOT / "src/dmsg_ios/Resources/Localizations").glob("*.lproj/Localizable.strings")):
        locale = source.parent.stem
        folder = "values" if locale == "en" else "values-in" if locale == "id" else "values-b+" + locale.replace("-", "+")
        target = ROOT / "src/dmsg_android/app/src/main/res" / folder / "notifications.xml"
        outputs[target] = render(plistlib.loads(source.read_bytes()))
    assert len(outputs) == 23, "Review the supported language set before changing it"
    extra = set((ROOT / "src/dmsg_android/app/src/main/res").glob("values*/notifications.xml")) - outputs.keys()
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items() if not p.exists() or p.read_text() != text] + [str(p.relative_to(ROOT)) for p in extra]
        if stale:
            raise SystemExit("Stale notification vocabulary: " + ", ".join(stale))
    else:
        for path in extra:
            path.unlink()
        for path, text in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    print(f"{'Checked' if args.check else 'Synced'} {len(outputs)} notification languages")
