#!/usr/bin/env python3
"""Generate Android resources from public iOS vocabulary and Android translations.

No network access. --check detects stale resources; --complete also rejects any
missing translation. Draft translation provenance is reported separately.
"""
import argparse
import hashlib
import json
import pathlib
import plistlib
import re
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parents[3]
ANDROID = ROOT / "src/dmsg_android"
DATA = ANDROID / "localization"
RES = ANDROID / "app/src/main/res"
LOCALES = ["en", "zh-Hans", "zh-Hant", "ar", "bn", "de", "es", "fil", "fr", "hi", "id", "it", "ja", "ko", "ms", "nl", "pl", "pt-BR", "ru", "th", "tr", "ur", "vi"]
FORMAT = re.compile(r"%([1-9][0-9]*\$)?([sd])")


def placeholders(text):
    return sorted(FORMAT.findall(text.replace("%%", "")))


def xml_text(text):
    # Android quotes preserve leading/trailing whitespace in labels and separators.
    value = text.replace("\\", "\\\\").replace("\n", "\\n").replace("\t", "\\t").replace("'", "\\'").replace('"', '\\"')
    return '"' + escape(value) + '"'


def generate():
    catalog = json.loads((DATA / "catalog.json").read_text())
    plurals = json.loads((DATA / "plurals.json").read_text())
    outputs, coverage = {}, {}
    for locale in LOCALES:
        source = ROOT / "src/dmsg_ios/Resources/Localizations" / (locale + ".lproj/Localizable.strings")
        shared = plistlib.loads(source.read_bytes())
        translated = DATA / (locale + ".json")
        overrides = json.loads(translated.read_text()) if translated.exists() else {}
        assert not (overrides.keys() - catalog.keys()), f"Unknown {locale} translation keys"
        values, missing = {}, []
        reused = 0
        for name, item in catalog.items():
            assert re.fullmatch(r"[a-z][a-z0-9_]*", name), name
            if locale in item:
                text = item[locale]
            elif name in overrides:
                text = overrides[name]
            elif item.get("ios") in shared:
                text = item.get("ios_prefix", "") + shared[item["ios"]] + item.get("ios_suffix", "")
                reused += 1
            elif item.get("untranslated"):
                text = item["en"]
            else:
                missing.append(name)
                continue
            assert isinstance(text, str) and text, f"Empty {locale}:{name}"
            assert placeholders(text) == placeholders(item["en"]), f"Format mismatch {locale}:{name}"
            values[name] = text
        # Android resource matching uses the legacy Indonesian language code,
        # even though Locale/localeConfig and our source catalog use BCP-47 id.
        folder = "values" if locale == "en" else "values-in" if locale == "id" else "values-b+" + locale.replace("-", "+")
        lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/sync-localizations.py. Edit localization/ or the shared iOS source. -->', '<resources>']
        for name, value in sorted(values.items()):
            formatted = "true" if placeholders(value) else "false"
            lines.append(f'    <string name="{name}" formatted="{formatted}">{xml_text(value)}</string>')
        for name, translations in sorted(plurals.items()):
            forms = translations[locale]
            assert "other" in forms, f"Missing other plural {locale}:{name}"
            lines.append(f'    <plurals name="{name}">')
            for form, text in forms.items():
                assert form in {"zero", "one", "two", "few", "many", "other"}
                assert placeholders(text) == [("1$", "s")], f"Invalid plural argument {locale}:{name}:{form}"
                lines.append(f'        <item quantity="{form}">{xml_text(text)}</item>')
            lines.append('    </plurals>')
        outputs[RES / folder / "strings.xml"] = "\n".join(lines + ["</resources>", ""])
        coverage[locale] = {"strings": len(values), "ios_reused": reused, "android_translations": len(overrides), "missing": missing, "ios_sha256": hashlib.sha256(source.read_bytes()).hexdigest()}
    outputs[RES / "xml/locales_config.xml"] = '\n'.join(['<?xml version="1.0" encoding="utf-8"?>', '<locale-config xmlns:android="http://schemas.android.com/apk/res/android">'] + [f'    <locale android:name="{locale}" />' for locale in LOCALES] + ['</locale-config>', ''])
    outputs[DATA / "coverage.json"] = json.dumps(coverage, ensure_ascii=False, indent=2) + "\n"
    return outputs, coverage


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--complete", action="store_true")
    args = parser.parse_args()
    outputs, coverage = generate()
    obsolete = [p for p in RES.glob("values*/strings.xml") if p not in outputs
                and "Generated by tools/sync-localizations.py." in p.read_text()]
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        stale.extend(str(p.relative_to(ROOT)) for p in obsolete)
        if stale:
            raise SystemExit("Stale resources: " + ", ".join(stale))
    else:
        for path in obsolete:
            path.unlink()
        for path, text in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    for locale, row in coverage.items():
        print(f"{locale}: {row['strings']} strings, {len(row['missing'])} untranslated")
    if args.complete and any(row["missing"] for row in coverage.values()):
        raise SystemExit("Translation coverage is incomplete; see localization/coverage.json")
