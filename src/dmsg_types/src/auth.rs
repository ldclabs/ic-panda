//! Public contracts of dmsg_auth. Times are Unix milliseconds except delegation expiration.
use crate::{Hash, MINUTE, user::AdmissionTicket};
use candid::{CandidType, Principal};
use serde::{Deserialize, Serialize};
use serde_bytes::ByteBuf;

/// Fixed lifetime of an issued delegation.
pub const AUTH_TTL_MS: u64 = 12 * 60 * MINUTE;
/// Lifetime of a one-use interactive challenge.
pub const CHALLENGE_TTL_MS: u64 = 5 * MINUTE;
/// Maximum remembered devices per login identity.
pub const MAX_AUTH_SESSIONS: usize = 16;
/// The relying party of the first-party login.
pub const PASSKEY_RP: &str = "dmsg.net";
/// Allowed WebAuthn client origin.
pub const PASSKEY_ORIGIN: &str = "https://dmsg.net";

/// An interactive operation. A challenge authorizes exactly one variant.
#[derive(CandidType, Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
pub enum AuthAction {
    /// Create a new single-passkey identity.
    #[serde(rename = "register")]
    Register,
    /// Remember this device for an existing identity.
    #[serde(rename = "login")]
    Login,
    /// End every session of the passkey's identity, including this one.
    #[serde(rename = "logout_all")]
    LogoutAll,
}

/// Basic service admission and execution budgets, not capacity promises.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct AuthLimits {
    /// Maximum stored identities.
    pub max_identities: u64,
    /// New identities per UTC day.
    pub daily_registrations: u32,
    /// Interactive requests per minute, challenges included.
    /// Preparation uses at most half this budget (minimum one).
    pub requests_per_minute: u32,
    /// Renewals per minute across the service.
    pub renewals_per_minute: u32,
    /// Simultaneously pending one-use challenges.
    pub max_challenges: u32,
}

/// Install arguments; identity salt is generated by the canister.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct AuthInit {
    /// Fixed governance allowed to administer alongside controllers.
    pub governance: Principal,
    /// Admission issuer's Ed25519 key; None only for unrestricted deployments.
    pub admission_key: Option<Hash>,
    /// Initial budgets.
    pub limits: AuthLimits,
}

/// A hardware caller asks for one interactive operation.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct ChallengeRequest {
    /// P-256 SPKI DER; its self-authenticating Principal must be the caller.
    pub public_key: ByteBuf,
    /// Operation to authorize.
    pub action: AuthAction,
}

/// Server-generated challenge, bound to the caller and operation.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct AuthChallenge {
    /// Unpredictable challenge bytes given to WebAuthn.
    pub challenge: Hash,
    /// Exclusive expiration, in milliseconds.
    pub expires_at: u64,
    /// Bound operation.
    pub action: AuthAction,
}

/// The browser or native authenticator's response, with exact signed bytes.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct PasskeyResponse {
    /// Raw credential ID, also present in registration authenticator data.
    pub credential_id: ByteBuf,
    /// Exact clientDataJSON bytes.
    pub client_data_json: ByteBuf,
    /// Registration: attestationObject; assertions: authenticatorData.
    pub authenticator_data: ByteBuf,
    /// Assertion DER ES256 signature; empty for registration with none attestation.
    pub signature: ByteBuf,
}

/// Registration additionally carries the existing account-admission ticket format.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct RegisterPasskey {
    /// One-use challenge returned for this caller.
    pub challenge: Hash,
    /// WebAuthn creation result.
    pub response: PasskeyResponse,
    /// Ticket bound to this canister and the hardware caller.
    pub admission: Option<AdmissionTicket>,
}

/// Login or logout-all assertion.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct AuthenticatePasskey {
    /// One-use challenge returned for this caller.
    pub challenge: Hash,
    /// WebAuthn assertion result.
    pub response: PasskeyResponse,
}

/// A delegation signed by the auth canister, addressed to the device key.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct AuthDelegation {
    /// Canister-signature public key, determining the login Principal.
    pub user_key: ByteBuf,
    /// Device public key in SPKI DER.
    pub public_key: ByteBuf,
    /// Exclusive expiration in IC nanoseconds.
    pub expiration: u64,
    /// Certified canister signature; obtained through get_delegation.
    pub signature: ByteBuf,
}

/// Public service statistics; no user or credential inventory.
#[derive(CandidType, Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct AuthStats {
    /// Stored identities.
    pub identities: u64,
    /// Stored sessions.
    pub sessions: u64,
    /// Pending interactive challenges.
    pub challenges: u64,
    /// Whether initialization has produced the identity salt.
    pub ready: bool,
    /// Whether registration requires a cloud admission ticket.
    pub admission_required: bool,
    /// Current admission budgets.
    pub limits: AuthLimits,
    /// Stable memory pages.
    pub stable_pages: u64,
    /// Canister cycle balance.
    pub cycles: u128,
}

/// Fragment request to the first-party browser page; it never handles K_dev's secret.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct PasskeyRequest {
    /// Literal protocol discriminator.
    pub protocol: String,
    /// Local callback correlation value.
    pub state: Hash,
    /// Auth service's interactive challenge.
    pub challenge: AuthChallenge,
    /// Loopback or associated-domain callback.
    pub next_url: String,
    /// Only logout-all restricts the selected credential; login is discoverable.
    pub credential_id: Option<ByteBuf>,
}

/// Fragment result returned to the client host.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct PasskeyCallback {
    /// Literal dmsg-passkey/1.
    pub protocol: String,
    /// Request's correlation value.
    pub state: Hash,
    /// WebAuthn response on success.
    pub response: Option<PasskeyResponse>,
    /// Bounded public failure code, without exception details.
    pub error: Option<String>,
}
