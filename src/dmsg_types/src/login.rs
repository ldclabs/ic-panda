//! dmsg-login/1: Internet Identity login relayed by `https://dmsg.net/_/login`
//! for local clients. Each message travels in a URL fragment as
//! base64url(canonical CBOR); see `docs/protocol/login-v1_zh.md`.
use crate::Hash;
use serde::{Deserialize, Serialize};
use serde_bytes::ByteBuf;

/// Protocol version carried as `v` in every message.
pub const LOGIN_VERSION: u8 = 1;

/// A client's login request, opened by the login page.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct LoginRequest {
    /// Protocol version, [`LOGIN_VERSION`].
    pub v: u8,
    /// Nonzero one-time value generated by the client.
    pub state: Hash,
    /// SPKI DER of the client's Ed25519 session key (44 bytes).
    pub session_pubkey: ByteBuf,
    /// Canister Principal texts the delegation is limited to, 1 to 32.
    pub targets: Vec<String>,
    /// Requested delegation lifetime in milliseconds.
    pub ttl_ms: u64,
    /// `https://dmsg.net` or the legacy `https://panda.fans`.
    pub derivation_origin: String,
    /// Loopback callback URL of the client.
    pub next_url: String,
}

/// A delegation issued to the session key.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct LoginResult {
    /// Protocol version, [`LOGIN_VERSION`].
    pub v: u8,
    /// The request's `state`.
    pub state: Hash,
    /// UTF-8 JSON of `DelegationChain.toJSON()` in the `@icp-sdk/core` format.
    pub delegation: ByteBuf,
}

/// Why the login page could not obtain a delegation.
#[derive(Serialize, Deserialize, Clone, Copy, Debug, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum LoginErrorCode {
    /// The user closed or cancelled Internet Identity.
    UserCancelled,
    /// Internet Identity returned an error.
    IiError,
    /// Internet Identity refused the derivation origin.
    DerivationOriginNotAllowed,
    /// Internet Identity did not answer in time.
    Timeout,
}

/// A failed login.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(deny_unknown_fields)]
pub struct LoginError {
    /// Protocol version, [`LOGIN_VERSION`].
    pub v: u8,
    /// The request's `state`.
    pub state: Hash,
    /// The reason.
    pub error: LoginErrorCode,
}

/// The body the client's callback page posts: a result or an error.
#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
#[serde(untagged)]
pub enum LoginCallback {
    /// A delegation.
    Result(LoginResult),
    /// A failure.
    Error(LoginError),
}
