        let mut replies = vec![
            ("GET", path.clone(), staging.clone()),
            ("PUT", format!("{path}/chunks/manifest"), reply(json!({}))),
            ("POST", format!("{base}/uploads/finalize"), None),
        ];
        if committed {
            replies.push((
                "GET",
                path,
                reply(json!({"status": "committed", "plan": job.vault.plan})),
            ));
        } else {
            replies.extend([
                ("GET", path.clone(), staging),
                ("PUT", format!("{path}/chunks/manifest"), reply(json!({}))),
                ("POST", format!("{base}/uploads/finalize"), None),
            ]);
        }
